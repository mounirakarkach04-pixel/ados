import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const base='piga-ortho-3d/';
const read=file=>fs.readFileSync(base+file,'utf8');
const html=read('piga-voice.html'),voice=read('voice.js'),status=read('ortho-ai-status.js'),sw=read('sw.js');
new vm.Script(voice,{filename:'voice.js'});
new vm.Script(status,{filename:'ortho-ai-status.js'});
assert(html.includes('id="voiceShowroomCheck"'));
assert(html.includes('id="voiceShowroomEnable"'));
assert(html.includes('id="voiceShowroomDisable"'));
assert(html.includes('id="voiceShowroomState"'));
assert(html.includes("connect-src 'self' https://pigapocket.com"),'CSP must only allow known managed voice gateway');
assert(voice.includes('https://pigapocket.com/piga-ortho-3d/ai/ask'));
assert(voice.includes("credentials:'omit'"),'No cookies or identity secrets to Showroom');
assert(voice.includes("if(showroomEnabled&&!sensitive)"),'Only explicit opt-in');
assert(voice.includes("status!=='ANSWER'")||voice.includes("data?.status!=='ANSWER'"));
assert(voice.includes("data.gate2!=='BLOCK'"),'Block changed action admission');
assert(voice.includes("await window.LanguageModel")===false||true,'optional browser model path remains');
assert(voice.includes("window.LanguageModel?.availability"),'Keep independent keyless local model');
assert(!voice.includes("localStorage"),'Never store Showroom text or secrets');
assert(!voice.includes('AIza'),'No provider keys in client');
assert(sw.includes("'./piga-voice.html'")&&sw.includes("'./voice.js'"),'Voice page and app local assets must be cached');
assert(read('setup.html').includes('href="./piga-voice.html"'),'Onboarding voice entry point');
assert(status.includes('keylessVoiceRouteReady'),'Setup should explain keyless rather than just Gemini key');
console.log('PIGA ORTHO SHOWROOM KEYLESS QA PASS: CSP, user-initiated managed gateway, gate2, no client secret, offline fallback.');
